import os,threading
from contextlib import contextmanager
DB_URL = os.getenv('DATABASE_URL', '').strip()
DB_LOCK = threading.Lock()

@contextmanager
def wishes_db():
    if DB_URL.startswith(('postgres://','postgresql://')):
        import psycopg
        with psycopg.connect(DB_URL, connect_timeout=8) as connection:
            yield connection, '%s'
    else:
        raise RuntimeError('DATABASE_URL must be a Neon PostgreSQL connection string; SQLite fallback is disabled.')

def init_wishes():
    with wishes_db() as (db, placeholder):
        if placeholder == '%s':
            db.execute('CREATE TABLE IF NOT EXISTS public_wedding_wishes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) NOT NULL, message VARCHAR(1200) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)')
        db.execute("""CREATE TABLE IF NOT EXISTS wedding_wish_replies (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            wish_id BIGINT NOT NULL REFERENCES public_wedding_wishes(id) ON DELETE CASCADE,
            name VARCHAR(80) NOT NULL,
            message VARCHAR(1000) NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")
        db.commit()


