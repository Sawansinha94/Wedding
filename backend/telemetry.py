def session_uuid(value):
    try: return uuid.UUID(str(value))
    except (ValueError,TypeError,AttributeError): return None

def log_activity(session_id, action, context=''):
    sid=session_uuid(session_id)
    if sid is None or action not in EVENTS:return
    try:
        with wishes_db() as (db, _):
            db.execute('INSERT INTO wedding_site_activity(session_id,action,context) VALUES (%s,%s,%s)',(sid,action,str(context)[:160]))
            db.commit()
    except Exception:
        log.warning('Unable to log website action %s',action)

class VisitIn(BaseModel):
    session_id: str = Field(max_length=80)
    page_path: str = Field(default='/',max_length=500)
    referrer: str = Field(default='',max_length=1500)
    device_type: str = Field(default='',max_length=30)
    browser_name: str = Field(default='',max_length=80)
    operating_system: str = Field(default='',max_length=100)
    device_model: str = Field(default='',max_length=120)
    screen_width: int | None = Field(default=None,ge=0,le=100000)
    screen_height: int | None = Field(default=None,ge=0,le=100000)
    viewport_width: int | None = Field(default=None,ge=0,le=100000)
    viewport_height: int | None = Field(default=None,ge=0,le=100000)
    language: str = Field(default='',max_length=40)
    timezone: str = Field(default='',max_length=100)


def _location_from_request(request: Request, ip: str | None):
    # Trusted CDN country header, if configured; never trust arbitrary forwarded geo headers.
    country = request.headers.get('cf-ipcountry', '') if os.getenv('TRUST_CLOUDFLARE_GEO','false').lower() == 'true' else ''
    if not re.fullmatch(r'[A-Z]{2}',country):country=None
    region=city=country_name=None
    # Optional local GeoLite2 City MMDB; never sends visitor IP to an external service.
    db_path=os.getenv('GEOLITE2_CITY_DB','').strip()
    if db_path and ip:
        try:
            import geoip2.database
            with geoip2.database.Reader(db_path) as reader:
                result=reader.city(ip)
                country=result.country.iso_code or country
                country_name=result.country.name
                region=result.subdivisions.most_specific.name
                city=result.city.name
        except Exception:
            pass
    return country,country_name,region,city


def _request_ip(request: Request):
    # Proxy-headers should be configured by the hosting platform to establish request.client.
    # Do not trust client-supplied X-Forwarded-For or similar headers here.
    if os.getenv('LOG_VISITOR_IP','false').lower() != 'true':return None
    raw=request.client.host if request.client else None
    try:
        value=ipaddress.ip_address(raw)
        return str(value) if value.is_global else None
    except (ValueError,TypeError):return None

@router.post('/api/telemetry/visit',status_code=201)
def record_visit(payload: VisitIn, request: Request):
    sid=session_uuid(payload.session_id)
    if not sid:return {'ok':False}
    ip=_request_ip(request)
    country,country_name,region,city=_location_from_request(request,ip)
    user_agent=request.headers.get('user-agent','')[:1500]
    with wishes_db() as (db, _):
        db.execute("""INSERT INTO website_visits
          (session_id,page_path,referrer,device_type,browser_name,operating_system,device_model,
           user_agent,screen_width,screen_height,viewport_width,viewport_height,language,timezone,
           country_code,country_name,region_name,city_name,ip_address)
          VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
          (sid,payload.page_path[:500],payload.referrer[:1500] or None,payload.device_type[:30] or None,
           payload.browser_name or None,payload.operating_system or None,payload.device_model or None,
           user_agent or None,payload.screen_width,payload.screen_height,payload.viewport_width,payload.viewport_height,
           payload.language or None,payload.timezone or None,country,country_name,region,city,ip))
        db.commit()
    return {'ok':True}

class ActionIn(BaseModel):
    session_id: str = Field(max_length=80)
    action: str = Field(max_length=70)
    context: str = Field(default='',max_length=160)

@router.post('/api/telemetry/action',status_code=201)
def record_action(payload: ActionIn):
    if payload.action not in EVENTS or not session_uuid(payload.session_id):return {'ok':False}
    log_activity(payload.session_id,payload.action,payload.context)
    return {'ok':True}

class VisitorNameIn(BaseModel):
    session_id: str = Field(max_length=80)
    first_name: str = Field(min_length=2,max_length=80)

@router.post('/api/telemetry/visitor-name', status_code=201)
def record_visitor_name(payload: VisitorNameIn):
    from .visitor import quick_name
    from fastapi import HTTPException
    sid=session_uuid(payload.session_id)
    name=' '.join(payload.first_name.strip().split())
    if not sid or len(name.split())>2 or quick_name(name) != 'valid':
        raise HTTPException(status_code=422,detail='Please enter a valid first name.')
    with wishes_db() as (db, _):
        db.execute('INSERT INTO wedding_visitor_names(session_id,first_name,source) VALUES (%s,%s,%s)',(sid,name,'welcome'))
        db.commit()
    return {'ok':True,'first_name':name}
