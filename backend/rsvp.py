from fastapi import APIRouter,HTTPException
from .schemas import RSVPIn,RSVP_ATTENDANCE,RSVP_EVENTS
from .database import DB_LOCK,wishes_db
router=APIRouter()
def init_rsvps():
    with wishes_db() as (db, ph):
        if ph == '%s':
            db.execute("""CREATE TABLE IF NOT EXISTS wedding_rsvps (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                guest_name VARCHAR(120) NOT NULL,
                attendance VARCHAR(40) NOT NULL,
                event_name VARCHAR(80) NOT NULL,
                guest_count INTEGER NOT NULL CHECK (guest_count BETWEEN 1 AND 20),
                message VARCHAR(2000) NOT NULL DEFAULT '',
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )""")
        db.commit()


@router.post('/api/rsvp', status_code=201)
def submit_rsvp(payload: RSVPIn):
    name = payload.name.strip()
    if not name or payload.attendance not in RSVP_ATTENDANCE or payload.event not in RSVP_EVENTS:
        raise HTTPException(422, 'Please provide valid RSVP details.')
    with DB_LOCK, wishes_db() as (db, ph):
        if ph == '%s':
            row = db.execute("""INSERT INTO wedding_rsvps
                (guest_name,attendance,event_name,guest_count,message)
                VALUES (%s,%s,%s,%s,%s) RETURNING id""",
                (name,payload.attendance,payload.event,payload.guests,payload.message.strip())).fetchone()
            submission_id = row[0]
        # The normalized rsvp_responses table logs the same submission, linked to wedding_events.
        # "Both events" produces one response per ceremony. No guest record is invented:
        # guests requires verified contact details not collected by this form.
        event_keys={'Wedding Ceremony':['wedding'], 'Reception & Blessings':['reception'],
                    'Both events':['wedding','reception']}[payload.event]
        status='attending' if payload.attendance=='Joyfully accepts' else 'not_attending'
        for event_key in event_keys:
            db.execute('''INSERT INTO rsvp_responses
                (event_id,guest_name,attendance_status,party_size,message)
                SELECT event_id,%s,%s,%s,%s FROM wedding_events WHERE event_key=%s''',
                (name,status,payload.guests,payload.message.strip(),event_key))
        db.commit()
    return {'ok': True, 'rsvp_id': submission_id, 'message': 'Your RSVP has been received.'}
