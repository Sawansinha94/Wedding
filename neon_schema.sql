CREATE TABLE IF NOT EXISTS wedding_rsvps (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guest_name VARCHAR(120) NOT NULL,
 attendance VARCHAR(40) NOT NULL,
 event_name VARCHAR(80) NOT NULL,
 guest_count INTEGER NOT NULL CHECK (guest_count BETWEEN 1 AND 20),
 message VARCHAR(2000) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public_wedding_wishes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 message VARCHAR(1200) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS wedding_wish_replies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 wish_id BIGINT NOT NULL REFERENCES public_wedding_wishes(id) ON DELETE CASCADE,
 name VARCHAR(80) NOT NULL,
 message VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wedding_rsvps_created_at ON wedding_rsvps(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_wishes_created_at ON public_wedding_wishes(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_wish_replies_wish_id ON wedding_wish_replies(wish_id,id);
