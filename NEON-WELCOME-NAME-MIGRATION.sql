CREATE TABLE IF NOT EXISTS wedding_visitor_names (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id UUID NOT NULL,
 first_name VARCHAR(80) NOT NULL,
 source VARCHAR(24) NOT NULL DEFAULT 'welcome',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_wedding_visitor_names_session ON wedding_visitor_names(session_id,created_at DESC);
