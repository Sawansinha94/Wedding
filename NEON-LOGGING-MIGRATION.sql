CREATE TABLE IF NOT EXISTS wedding_site_activity (
 activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id UUID NOT NULL,
 action VARCHAR(70) NOT NULL,
 context VARCHAR(160),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_wedding_activity_session ON wedding_site_activity(session_id,created_at);
-- The application syncs the four event rows on startup. No other schema changes required.
