CREATE TABLE IF NOT EXISTS wedding_rsvps (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guest_name VARCHAR(120) NOT NULL,
 attendance VARCHAR(40) NOT NULL,
 event_name VARCHAR(80) NOT NULL,
 guest_count INTEGER NOT NULL CHECK (guest_count BETWEEN 1 AND 20),
 message VARCHAR(2000) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wedding_rsvps_created_at ON wedding_rsvps (created_at DESC);
